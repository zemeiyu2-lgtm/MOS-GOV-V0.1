#!/usr/bin/env bash
# =============================================================================
# MOS-GOV Phase 5 — HTTP tenant-boundary acceptance (REAL HTTP, REAL SQL, REAL FILES).
#
# Starts the PHP 8.4.25 built-in server on 127.0.0.1:<port> with router.php and
# drives it with real curl requests against the isolated MariaDB 11.8.9
# instance on 127.0.0.1:3407 (two separate databases, two separate storage
# roots, two separate accounts).
#
# HONESTY CONTRACT
#   This harness is NOT the full ChurchCRM 7.8.0 stack (no Slim router, no
#   Propel bootstrap, no Apache/TLS terminator). It proves the tenant-boundary
#   logic — host pinning, session/tenant binding, per-tenant SQL scoping,
#   registry-scoped file delivery, traversal rejection, CSRF/Origin enforcement
#   and security headers — against real infrastructure. Full-stack ChurchCRM
#   E2E and real-TLS behaviour are reported separately as NOT covered here.
#
# Usage:  http-tests.sh <protected-env.sh> <repo-root> <php.exe> <php.ini>
# Exit:   0 when every check passes, 1 otherwise.
# =============================================================================
set -uo pipefail

# A sandboxed/CI shell may inject http_proxy/HTTPS_PROXY. That would send the
# loopback requests to a proxy and yield 502 without ever reaching the server,
# which looks exactly like a product failure. Force direct connections.
export NO_PROXY='*' no_proxy='*'
unset HTTP_PROXY HTTPS_PROXY http_proxy https_proxy ALL_PROXY all_proxy 2>/dev/null || true

LAB_ENV="${1:?usage: http-tests.sh <env.sh> <repo-root> <php> <ini>}"
REPO="${2:?}"
PHP="${3:?}"
INI="${4:?}"

# shellcheck disable=SC1090
source "$LAB_ENV"

PORT="${MOSGOV_P5_HTTP_PORT:-8099}"
HOST_A="a.mosgov.example"
HOST_B="b.mosgov.example"
BASE_A="http://${HOST_A}:${PORT}"
BASE_B="http://${HOST_B}:${PORT}"
ROUTER_DIR="$REPO/tests/phase5/http-boundary"

TMP="$MOSGOV_P5_EVIDENCE/../lab/tmp/http"
rm -rf "$TMP" 2>/dev/null
mkdir -p "$TMP"

CURL=(curl -sS --max-time 15 --noproxy '*'
      --resolve "${HOST_A}:${PORT}:127.0.0.1"
      --resolve "${HOST_B}:${PORT}:127.0.0.1")

# Synthetic lab credentials are generated by seed-synthetic.php into each church's
# private storage root. Read them instead of hard-coding secrets in the repo.
cred_field() { sed -n "s/.*\"$2\":\"\([^\"]*\)\".*/\1/p" "$1" 2>/dev/null | head -1; }
LOGIN_A="$(cred_field "${MOSGOV_P5_STORAGE_A}/.p5-login.json" login)"
SECRET_A="$(cred_field "${MOSGOV_P5_STORAGE_A}/.p5-login.json" secret)"
LOGIN_B="$(cred_field "${MOSGOV_P5_STORAGE_B}/.p5-login.json" login)"
SECRET_B="$(cred_field "${MOSGOV_P5_STORAGE_B}/.p5-login.json" secret)"
if [ -z "$LOGIN_A" ] || [ -z "$SECRET_A" ] || [ -z "$LOGIN_B" ] || [ -z "$SECRET_B" ]; then
  echo "FATAL | 缺少合成登录凭据，请先运行 tests/phase5/seed-synthetic.php"
  exit 1
fi

PASS=0
FAIL=0
ok()  { PASS=$((PASS + 1)); printf 'PASS | %-46s | %s\n' "$1" "$2"; }
bad() { FAIL=$((FAIL + 1)); printf 'FAIL | %-46s | %s\n' "$1" "$2"; }

check() { # id-desc expected actual
  if [ "$2" = "$3" ]; then ok "$1" "expected=$2 actual=$3"
  else bad "$1" "expected=$2 actual=$3"; fi
}
has() { # id-desc needle file
  if grep -qF -- "$2" "$3" 2>/dev/null; then ok "$1" "found '$2'"
  else bad "$1" "missing '$2' in $(basename "$3")"; fi
}
hasnt() {
  if grep -qF -- "$2" "$3" 2>/dev/null; then bad "$1" "LEAKED '$2'"
  else ok "$1" "absent '$2'"; fi
}

# ---------------------------------------------------------------- start server
echo "--- http-boundary: starting PHP built-in server on 127.0.0.1:${PORT} ---"
"$PHP" -c "$INI" -t "$ROUTER_DIR" -S "127.0.0.1:${PORT}" "$ROUTER_DIR/router.php" \
  >"$TMP/server.log" 2>&1 &
SRV=$!
cleanup() { kill "$SRV" 2>/dev/null; wait "$SRV" 2>/dev/null; }
trap cleanup EXIT

UP=0
for _ in $(seq 1 25); do
  if "${CURL[@]}" -o /dev/null -w '%{http_code}' "$BASE_A/login" 2>/dev/null | grep -q '^200$'; then
    UP=1; break
  fi
  sleep 0.4
done
if [ "$UP" -ne 1 ]; then
  echo "FATAL | server did not become ready; server.log follows"
  sed -n '1,40p' "$TMP/server.log"
  exit 1
fi
echo "--- server ready (pid $SRV) ---"

# ------------------------------------------------------- H1 host pinning (deny)
c=$(curl -sS --max-time 10 --noproxy '*' --resolve "evil.example:${PORT}:127.0.0.1" \
      -o "$TMP/h1.json" -w '%{http_code}' "http://evil.example:${PORT}/login")
check "H1-01 未注册 Host 被拒绝" 403 "$c"
has   "H1-02 拒绝原因明确" "unregistered host" "$TMP/h1.json"

# 直连回环 IP 时 HTTP_HOST 是 IP:port，解析不出租户 → 必须拒绝。
c=$(curl -sS --max-time 10 --noproxy '*' -o "$TMP/h1c.json" -w '%{http_code}' "http://127.0.0.1:${PORT}/login")
check "H1-03 IP 直连（无租户 Host）被拒绝" 403 "$c"

# --------------------------------------------------------- H2 login page (A)
c=$("${CURL[@]}" -c "$TMP/jarA0.txt" -D "$TMP/h2.head" -o "$TMP/h2.html" \
      -w '%{http_code}' "$BASE_A/login")
check "H2-01 A 登录页可访问" 200 "$c"
has   "H2-02 页面绑定 church-a" "church-a" "$TMP/h2.html"
hasnt "H2-03 页面不泄露 church-b" "church-b" "$TMP/h2.html"
has   "H2-04 会话 Cookie HttpOnly" "HttpOnly" "$TMP/h2.head"
has   "H2-05 会话 Cookie SameSite=Lax" "SameSite=Lax" "$TMP/h2.head"

csrfA=$(sed -n 's/.*name="csrf" value="\([a-f0-9]\{32,64\}\)".*/\1/p' "$TMP/h2.html" | head -1)
if [ -n "$csrfA" ]; then ok "H2-06 CSRF token 已下发" "len=${#csrfA}"
else bad "H2-06 CSRF token 已下发" "no token in login page"; fi

# ------------------------------------------------------ H3/H4 login rejections
c=$("${CURL[@]}" -b "$TMP/jarA0.txt" -c "$TMP/jarA0.txt" -o "$TMP/h3.json" -w '%{http_code}' \
      -d "login=${LOGIN_A}&secret=${SECRET_A}" "$BASE_A/login")
check "H3-01 无 CSRF 的登录被拒绝" 403 "$c"
has   "H3-02 明确报 CSRF 失败" "csrf invalid" "$TMP/h3.json"

c=$("${CURL[@]}" -b "$TMP/jarA0.txt" -c "$TMP/jarA0.txt" -o "$TMP/h4.json" -w '%{http_code}' \
      -d "csrf=${csrfA}&login=${LOGIN_A}&secret=WRONG-SECRET" "$BASE_A/login")
check "H4-01 错误口令被拒绝" 401 "$c"
has   "H4-02 不提示账号是否存在" "bad credentials" "$TMP/h4.json"

# ------------------------------------------------------------- H5 valid login
preSid=$(awk '$6=="MOSGOVP5SESS"{print $7}' "$TMP/jarA0.txt" | tail -1)
c=$("${CURL[@]}" -b "$TMP/jarA0.txt" -c "$TMP/jarA.txt" -o "$TMP/h5.json" -w '%{http_code}' \
      -d "csrf=${csrfA}&login=${LOGIN_A}&secret=${SECRET_A}" "$BASE_A/login")
check "H5-01 A 正确凭据登录成功" 200 "$c"
has   "H5-02 会话绑定 church-a" '"tenant":"church-a"' "$TMP/h5.json"
sidA=$(sed -n 's/.*"sid":"\([a-f0-9]\{16,\}\)".*/\1/p' "$TMP/h5.json" | head -1)
if [ -n "$sidA" ] && [ "$sidA" != "$preSid" ]; then
  ok "H5-03 登录后会话 ID 已重置（防固定攻击）" "sid rotated"
else
  bad "H5-03 登录后会话 ID 已重置（防固定攻击）" "pre=${preSid:-none} post=${sidA:-none}"
fi

# ------------------------------------------- H6 cross-host session replay (B)
c=$("${CURL[@]}" -H "Cookie: MOSGOVP5SESS=${sidA}" -o "$TMP/h6.json" -w '%{http_code}' \
      "$BASE_B/api/members")
check "H6-01 A 的会话在 B 主机上无效" 401 "$c"
has   "H6-02 明确拒绝跨租户会话" "foreign tenant session" "$TMP/h6.json"

# ---------------------------------------------------- H7/H8 A data scoping
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h7.json" -w '%{http_code}' "$BASE_A/api/members")
check "H7-01 A 已登录可读成员" 200 "$c"
n=$(grep -o '"person_id"' "$TMP/h7.json" | wc -l | tr -d ' ')
check "H7-02 A 只返回本会 3 名成员" 3 "$n"
# mysqli 以字符串返回整数列，因此 JSON 中 person_id 为 "1001" 形式。
has   "H7-03 含 A 成员 1001" '"person_id":"1001"' "$TMP/h7.json"
hasnt "H7-04 不含 B 成员 2001" '"person_id":"2001"' "$TMP/h7.json"
hasnt "H7-05 不含 B 成员姓名" "Member B-" "$TMP/h7.json"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h8.json" -w '%{http_code}' "$BASE_A/api/governance")
check "H8-01 A 已登录可读治理决议" 200 "$c"
n=$(grep -o '"id":' "$TMP/h8.json" | wc -l | tr -d ' ')
check "H8-02 A 只返回本会 2 条决议" 2 "$n"
has   "H8-03 含 A 决议" "SYNTHETIC A 决议一" "$TMP/h8.json"
hasnt "H8-04 不含 B 决议" "SYNTHETIC B" "$TMP/h8.json"

# ------------------------------------------------------- H9 mirror check (B)
c=$("${CURL[@]}" -c "$TMP/jarB0.txt" -o "$TMP/h9.html" -w '%{http_code}' "$BASE_B/login")
check "H9-01 B 登录页可访问" 200 "$c"
has   "H9-02 页面绑定 church-b" "church-b" "$TMP/h9.html"
csrfB=$(sed -n 's/.*name="csrf" value="\([a-f0-9]\{32,64\}\)".*/\1/p' "$TMP/h9.html" | head -1)
c=$("${CURL[@]}" -b "$TMP/jarB0.txt" -c "$TMP/jarB.txt" -o "$TMP/h9b.json" -w '%{http_code}' \
      -d "csrf=${csrfB}&login=${LOGIN_B}&secret=${SECRET_B}" "$BASE_B/login")
check "H9-03 B 正确凭据登录成功" 200 "$c"
c=$("${CURL[@]}" -b "$TMP/jarB.txt" -o "$TMP/h9c.json" -w '%{http_code}' "$BASE_B/api/members")
check "H9-04 B 已登录可读成员" 200 "$c"
has   "H9-05 含 B 成员 2001" '"person_id":"2001"' "$TMP/h9c.json"
hasnt "H9-06 不含 A 成员 1001（反向校验）" '"person_id":"1001"' "$TMP/h9c.json"

# ------------------------------------------------ H10/H11 file delivery scope
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -D "$TMP/h10.head" -o "$TMP/h10.txt" -w '%{http_code}' \
      "$BASE_A/api/files/minutes-A-2026-04.txt")
check "H10-01 A 可下载本会已登记文件" 200 "$c"
has   "H10-02 内容属于 church-a" "church-a" "$TMP/h10.txt"
shaLocal=$(sha256sum "$MOSGOV_P5_STORAGE_A/minutes-A-2026-04.txt" | cut -d' ' -f1)
shaHdr=$(grep -i '^X-File-Sha256:' "$TMP/h10.head" | awk '{print $2}' | tr -d '\r')
check "H10-03 响应头 SHA256 与磁盘一致" "$shaLocal" "$shaHdr"

c=$("${CURL[@]}" -b "$TMP/jarB.txt" -o "$TMP/h11b.txt" -w '%{http_code}' \
      "$BASE_B/api/files/minutes-B-2026-04.txt")
check "H11-01 B 可下载 B 的文件（证明键真实存在）" 200 "$c"
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h11.json" -w '%{http_code}' \
      "$BASE_A/api/files/minutes-B-2026-04.txt")
check "H11-02 A 跨会取 B 已登记键 → 404" 404 "$c"
has   "H11-03 失败不区分「不存在」与「无权限」" "not registered for this tenant" "$TMP/h11.json"

# ------------------------------------------------------ H12-H15 key hardening
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h12.json" -w '%{http_code}' \
      "$BASE_A/api/files/%2e%2e%2fstorage-b%2fminutes-B-2026-04.txt")
check "H12-01 编码目录穿越被拒绝" 403 "$c"
has   "H12-02 报非法对象键" "invalid object key" "$TMP/h12.json"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h13.json" -w '%{http_code}' \
      "$BASE_A/api/files/%2e%2e%2f%2e%2e%2fetc%2fpasswd")
check "H13-01 多级穿越被拒绝" 403 "$c"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h14.json" -w '%{http_code}' \
      "$BASE_A/api/files/%2Fetc%2Fpasswd")
check "H14-01 绝对路径键被拒绝" 403 "$c"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h15.json" -w '%{http_code}' \
      "$BASE_A/api/files/")
check "H15-01 空对象键被拒绝" 403 "$c"

# --------------------------------------------------- H16-H18 session/CSRF
c=$("${CURL[@]}" -o "$TMP/h16.json" -w '%{http_code}' "$BASE_A/api/members")
check "H16-01 未登录读取成员被拒绝" 401 "$c"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -c "$TMP/jarA.txt" -o "$TMP/h17.json" -w '%{http_code}' \
      -H "Origin: http://${HOST_B}" -d "csrf=${csrfA}" "$BASE_A/login")
check "H17-01 跨站 Origin 的写请求被拒绝" 403 "$c"
has   "H17-02 报跨站来源" "cross-origin rejected" "$TMP/h17.json"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h18.json" -w '%{http_code}' \
      -d "x=1" "$BASE_A/api/members")
check "H18-01 已登录但无 CSRF 的写请求被拒绝" 403 "$c"
has   "H18-02 报 CSRF 失败" "csrf invalid" "$TMP/h18.json"

# ------------------------------------------------------- H19 security headers
for h in "X-Frame-Options: DENY" "X-Content-Type-Options: nosniff" \
         "frame-ancestors 'none'" "Strict-Transport-Security: max-age=31536000" \
         "Cache-Control: no-store"; do
  has "H19 安全响应头 ${h%%:*}" "$h" "$TMP/h2.head"
done

# ------------------------------------------------------------ H20 404 + logout
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h20.json" -w '%{http_code}' "$BASE_A/api/unknown")
check "H20-01 未知路径返回 404" 404 "$c"

c=$("${CURL[@]}" -b "$TMP/jarA.txt" -c "$TMP/jarA.txt" -o "$TMP/h21.json" -w '%{http_code}' \
      "$BASE_A/logout")
check "H21-01 登出成功" 200 "$c"
c=$("${CURL[@]}" -b "$TMP/jarA.txt" -o "$TMP/h22.json" -w '%{http_code}' "$BASE_A/api/members")
check "H21-02 登出后会话立即失效" 401 "$c"

echo "--- http-boundary: ${PASS} PASS / ${FAIL} FAIL ---"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
